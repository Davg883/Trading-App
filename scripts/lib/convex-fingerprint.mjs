// Sprint G9.2 — deterministic fingerprint of everything the Convex backend executes.
//
// Root cause it guards against: the Vercel build deploys only the Next.js frontend (`next build`), so a frontend built
// from commit X ran against Convex functions built from an older commit. The function *names* were identical, so the
// mismatch was invisible until research output was wrong. The fingerprint hashes the full import closure of the
// Convex functions (convex/*.ts plus every relative module and JSON file they reach in lib/, data/, ...) and the
// installed versions of the npm packages that closure imports. The same value is compiled into the frontend (via
// convex/deploymentFingerprint.ts) and returned by the deployed backend (`release:fingerprint`), so equality proves the
// running backend was built from the same sources the frontend expects.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

export const FINGERPRINT_CONTRACT_VERSION = 'aci-convex-fingerprint-v1';
export const FINGERPRINT_FILE = 'convex/deploymentFingerprint.ts';
const EXTENSIONS = ['', '.ts', '.tsx', '.js', '.mjs', '.cjs', '.json'];
const INDEX_FILES = ['index.ts', 'index.tsx', 'index.js'];
const IMPORT_RE = /(?:import|export)\s[^'"`;]*?from\s*['"]([^'"]+)['"]|import\s*\(\s*['"]([^'"]+)['"]\s*\)|import\s+['"]([^'"]+)['"]|require\s*\(\s*['"]([^'"]+)['"]\s*\)/g;

const toPosix = (p) => p.split(path.sep).join('/');
const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

function resolveRelative(fromFile, spec) {
  const base = path.resolve(path.dirname(fromFile), spec);
  for (const ext of EXTENSIONS) {
    const candidate = base + ext;
    if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate;
  }
  for (const idx of INDEX_FILES) {
    const candidate = path.join(base, idx);
    if (fs.existsSync(candidate)) return candidate;
  }
  return null;
}

function packageName(spec) {
  if (spec.startsWith('node:')) return null;
  const parts = spec.split('/');
  return spec.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
}

/** Convex entry modules: every .ts/.js file under convex/ except generated code and the fingerprint file itself. */
function entryFiles(root) {
  const dir = path.join(root, 'convex');
  const out = [];
  const walk = (d) => {
    for (const name of fs.readdirSync(d)) {
      const full = path.join(d, name);
      const rel = toPosix(path.relative(root, full));
      if (fs.statSync(full).isDirectory()) {
        if (name === '_generated' || name === 'node_modules') continue;
        walk(full);
      } else if (/\.(ts|js)$/.test(name) && rel !== FINGERPRINT_FILE && !name.endsWith('.d.ts')) {
        out.push(full);
      }
    }
  };
  walk(dir);
  return out;
}

/**
 * Computes the fingerprint for the repository at `root`.
 * @returns {{contractVersion:string, sourceSha256:string, fileCount:number, packageCount:number, files:string[], packages:string[]}}
 */
export function computeConvexFingerprint(root = process.cwd()) {
  const seen = new Set();
  const packages = new Set();
  const queue = entryFiles(root);
  while (queue.length) {
    const file = queue.pop();
    if (seen.has(file)) continue;
    seen.add(file);
    if (file.endsWith('.json')) continue;
    const src = fs.readFileSync(file, 'utf8');
    for (const m of src.matchAll(IMPORT_RE)) {
      const spec = m[1] ?? m[2] ?? m[3] ?? m[4];
      if (!spec) continue;
      if (spec.startsWith('.')) {
        const resolved = resolveRelative(file, spec);
        if (resolved && toPosix(path.relative(root, resolved)) !== FINGERPRINT_FILE && !toPosix(resolved).includes('/convex/_generated/')) {
          queue.push(resolved);
        }
      } else {
        const name = packageName(spec);
        if (name) packages.add(name);
      }
    }
  }
  const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
  const packageLines = [...packages]
    .sort()
    .map((name) => `${name}@${lock.packages?.[`node_modules/${name}`]?.version ?? 'unresolved'}`);
  const files = [...seen].map((f) => toPosix(path.relative(root, f))).sort();
  const lines = files.map((rel) => {
    const content = fs.readFileSync(path.join(root, rel), 'utf8').replace(/\r\n/g, '\n');
    return `${rel}\t${sha256(content)}`;
  });
  const sourceSha256 = sha256([FINGERPRINT_CONTRACT_VERSION, ...lines, ...packageLines].join('\n'));
  return {
    contractVersion: FINGERPRINT_CONTRACT_VERSION,
    sourceSha256,
    fileCount: files.length,
    packageCount: packageLines.length,
    files,
    packages: packageLines,
  };
}

export function renderFingerprintModule(fp) {
  return `// AUTO-GENERATED by scripts/write-convex-fingerprint.mjs (npm run convex:fingerprint). Do not edit by hand.
// Hash of the Convex functions' full import closure and imported package versions. The frontend compiles this value
// in; the deployed backend returns it from \`release:fingerprint\`. They must match for a release to be accepted.
export const CONVEX_DEPLOYMENT_FINGERPRINT = {
  contractVersion: '${fp.contractVersion}',
  sourceSha256: '${fp.sourceSha256}',
  fileCount: ${fp.fileCount},
  packageCount: ${fp.packageCount},
} as const;
`;
}
