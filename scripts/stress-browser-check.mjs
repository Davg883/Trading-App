import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true,channel:'msedge'});
try {
  fs.mkdirSync('test-results',{recursive:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:3000/stress');
  await expect(page.getByRole('heading',{name:/Price has changed/})).toBeVisible();
  await expect(page.getByText('Observed-data workspace — no live provider connected.',{exact:true})).toBeVisible();
  for(const symbol of ['GOOGL','AMZN','MSFT','NVDA','INTC','CRWV']) await expect(page.locator('tbody').getByText(symbol,{exact:true})).toBeVisible();
  await expect(page.locator('tbody').getByText('No sourced quote',{exact:true})).toHaveCount(6);
  await expect(page.getByText('−$9.065bn',{exact:true})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Insufficient evidence',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Observed research',exact:true}).click();
  await page.screenshot({path:'test-results/stress-observed-desktop.png',caret:'initial'});
  await page.getByRole('button',{name:'Synthetic demonstration',exact:true}).click();
  await expect(page.getByText('Synthetic demonstration — every market price below is invented.',{exact:true})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Insufficient evidence',exact:true})).toBeVisible();
  await expect(page.locator('tbody').getByText('No sourced quote',{exact:true})).toHaveCount(0);
  await expect(page.getByText('−$9.065bn',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Register retrospective windows',exact:true}).click();
  await expect(page.locator('.stress-window').getByText('completed',{exact:true})).toHaveCount(2);
  await expect(page.locator('.stress-window').getByText('pending',{exact:true})).toHaveCount(2);
  const waitDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download synthetic import-format example',exact:true}).click();
  const samplePath='test-results/stress-synthetic-format.json';await (await waitDownload).saveAs(samplePath);
  await page.getByLabel('Import licensed market JSON').setInputFiles(samplePath);
  await expect(page.getByRole('status')).toContainText('Observed import rejects synthetic datasets');
  const waitDraft=page.waitForEvent('download');
  await page.getByRole('button',{name:'Freeze & export research draft',exact:true}).click();
  await (await waitDraft).saveAs('test-results/stress-research-draft.json');
  const draft=JSON.parse(fs.readFileSync('test-results/stress-research-draft.json','utf8'));
  if(draft.synthetic!==true||draft.executionAuthority!=='none')throw new Error('Research draft lost synthetic or authority label');
  await page.getByText('Record an independent research assessment',{exact:true}).click();
  await page.getByLabel('Fundamental outlook').selectOption('stable');
  await page.getByLabel('Valuation assessment').selectOption('reset');
  await page.getByLabel('Supporting evidence · one exact source ID per line').fill('synthetic-reviewed-source');
  await page.getByLabel('I have reviewed the original sources, eligibility and conflicting evidence.').check();
  await expect(page.getByRole('heading',{name:'Insufficient evidence',exact:true})).toBeVisible();
  await page.getByLabel('Unresolved uncertainties · one per line').fill('');
  await expect(page.getByRole('heading',{name:'Potential valuation opportunity',exact:true})).toBeVisible();
  await page.getByLabel('Fundamental outlook').selectOption('unknown');
  await expect(page.getByRole('heading',{name:'Insufficient evidence',exact:true})).toBeVisible();
  const reportPath='test-results/stress-end-to-end/report.json';
  await page.getByLabel('Import runner report JSON').setInputFiles(reportPath);
  await expect(page.getByRole('status')).toContainText('Imported local runner report');
  await expect(page.getByRole('cell',{name:/^openai/})).toBeVisible();
  await expect(page.getByRole('cell',{name:/^passive-QQQ/})).toBeVisible();
  const pending=JSON.parse(fs.readFileSync(reportPath,'utf8'));pending.outcome.status='pending';
  await page.getByLabel('Import runner report JSON').setInputFiles({name:'invalid-pending.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(pending))});
  await expect(page.getByRole('status')).toContainText('Pending outcomes cannot contain forecasting scores');
  await page.getByRole('button',{name:'Observed research',exact:true}).click();
  await page.getByLabel('Import runner report JSON').setInputFiles(reportPath);
  await expect(page.getByRole('status')).toContainText('Report data mode differs');
  await expect(page.getByRole('cell',{name:/^openai/})).toHaveCount(0);
  await page.getByRole('button',{name:'Synthetic demonstration',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'test-results/stress-mobile.png',caret:'initial'});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw new Error('Stress mobile overflow');
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('Stress browser checks passed: six companies, observed nulls, separate demo, no decline-only opportunity, aligned completed/pending windows, import rejection, export, mobile layout.');
}finally{await browser.close();}
