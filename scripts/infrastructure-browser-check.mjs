import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
const browser=await chromium.launch({headless:true,channel:'msedge'});
try{
  fs.mkdirSync('test-results',{recursive:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:3000/');
  await page.getByRole('button',{name:'Economics Observatory',exact:true}).click();
  await page.getByRole('link',{name:/AI Infrastructure Financing Dependency/}).click();
  await expect(page.getByRole('heading',{name:/Follow the funding/})).toBeVisible();
  await expect(page.getByText('Sourced retrospective research case.',{exact:true})).toBeVisible();
  await expect(page.locator('#financing-events tbody tr')).toHaveCount(6);
  const guaranteeRow=page.locator('#financing-events tbody tr').filter({hasText:'monarch-credit-talks'});
  await expect(guaranteeRow).toContainText('reported discussion');await expect(guaranteeRow).toContainText('Unavailable');
  await expect(page.locator('#financing-events tbody tr').filter({hasText:'texas-lease-guarantee'})).toContainText('USD 860.3m');
  await expect(page.locator('#financing-events tbody tr').filter({hasText:'microsoft-loughton-customer'})).toContainText('cancelled');
  await expect(page.locator('.infra-distinct').getByText('USD 103.4bn',{exact:true})).toBeVisible();
  await expect(page.locator('.infra-distinct').getByText('USD 140.6m',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Validate proposed transition',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Transition blocked');
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'test-results/infrastructure-desktop.png',caret:'initial'});
  await page.getByRole('button',{name:'After publication, before receipt',exact:true}).click();
  await expect(page.locator('#financing-events tbody tr')).toHaveCount(0);
  await expect(page.locator('.infra-map .infra-party')).toHaveCount(0);
  await expect(page.getByText('No eligible source evidence was available at this cutoff. Company-specific research conclusions remain unavailable.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Current sourced review',exact:true}).click();
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export offline evaluation',exact:true}).click();
  const requestPath='test-results/infrastructure-ui-request.json';await (await download).saveAs(requestPath);
  const run=spawnSync('python',['-m','worker.infrastructure_financing',requestPath],{encoding:'utf8'});
  if(run.status!==0)throw new Error(run.stderr||run.stdout||'Infrastructure worker failed');
  const report=JSON.parse(run.stdout);
  if(report.executionAuthority!=='none')throw new Error('Research report gained execution authority');
  fs.writeFileSync('test-results/infrastructure-ui-report.json',JSON.stringify(report,null,2));
  const repeat=spawnSync('python',['-m','worker.infrastructure_financing',requestPath],{encoding:'utf8'});
  if(repeat.status!==0||repeat.stdout!==run.stdout)throw new Error('Infrastructure evaluation is not reproducible');
  await page.getByLabel('Relationship evidence').selectOption('verified_contract');
  await expect(page.locator('.infra-link').filter({hasText:'reported discussion'})).toHaveCount(0);
  await page.getByLabel('Commitment type').selectOption('equity_investment');
  await expect(page.getByText('No eligible relationship of this type is registered. Missing proof does not create an inferred verified contract.',{exact:true})).toBeVisible();
  await page.getByLabel('Relationship evidence').selectOption('all');await page.getByLabel('Commitment type').selectOption('all');
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'test-results/infrastructure-mobile.png',caret:'initial'});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Infrastructure mobile overflow');
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('Infrastructure browser checks passed: Observatory navigation, sourced statuses, distinct metrics, blocked promotion, receipt cutoff, relationship filters, Python handoff/reproducibility and mobile layout.');
}finally{await browser.close();}
