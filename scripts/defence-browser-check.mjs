import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
const browser=await chromium.launch({headless:true,channel:'msedge'});
try{
  fs.mkdirSync('test-results',{recursive:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:3000/');
  await page.getByRole('button',{name:'Paper Trading',exact:true}).click();
  await page.getByRole('link',{name:/Portfolio Defence & Hedging/}).click();
  await expect(page.getByRole('heading',{name:/Protect the portfolio/})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Evidence required before calculation'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Export research package'})).toBeDisabled();
  await expect(page.getByText('Private research reviews are not connected.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Synthetic demonstration',exact:true}).click();
  await expect(page.getByTestId('defence-mode')).toContainText('all instruments, holdings, prices and shock returns are invented');
  await expect(page.locator('#exposure .defence-summary').getByText('84.00%',{exact:true})).toBeVisible();
  await expect(page.locator('#exposure .defence-summary').getByText('4.00%',{exact:true})).toBeVisible();
  const table=page.getByRole('table',{name:'Matched portfolio stress results'});
  await expect(table.getByRole('cell',{name:'£10,000.00',exact:true})).toHaveCount(3);
  await expect(page.locator('#history')).toContainText('70 aligned daily returns');
  await expect(page.getByTestId('option-result')).toContainText('Pending expiry settlement');
  await page.getByLabel('Use illustrative exact-expiry settlement').check();
  await expect(page.getByTestId('option-result')).toContainText('-£1,405.00');
  await expect(page.getByTestId('inverse-result')).toContainText('-1.82%');
  await page.getByRole('button',{name:'AI recovery and renewed growth',exact:true}).click();
  await expect(page.locator('#scenarios')).toContainText('ai recovery');
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export research package'}).click();
  const file=await download;await file.saveAs('test-results/defence-ui-export.json');
  const request=JSON.parse(fs.readFileSync('test-results/defence-ui-export.json','utf8'));
  const run=()=>spawnSync('python',['-m','worker.portfolio_defence','test-results/defence-ui-export.json'],{encoding:'utf8'});
  const first=run(),second=run();if(first.status!==0)throw new Error(first.stderr);
  expect(second.status).toBe(0);expect(first.stdout).toBe(second.stdout);
  const report=JSON.parse(first.stdout);expect(report.exposure.aiWeight).toBeCloseTo(.84);expect(report.comparison.baseline.initialCapital).toBe(report.comparison.alternative.initialCapital);expect(report.history.samples).toBe(70);
  await expect(page.getByTestId('net-protection')).toHaveText(new Intl.NumberFormat('en-GB',{style:'currency',currency:'GBP',maximumFractionDigits:2}).format(report.comparison.netProtection));
  await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'test-results/defence-desktop.png',caret:'initial'});
  const cutoff=page.getByLabel('Evidence cutoff · ISO timestamp with timezone');await cutoff.fill('1969-12-31T23:59:59Z');
  await expect(page.locator('.defence-error[role=alert]')).toContainText('valid cutoff');await expect(page.getByRole('button',{name:'Export research package'})).toBeDisabled();
  await page.getByRole('button',{name:'Synthetic demonstration',exact:true}).click();
  request.case.portfolios[1].initialCapital=9999;
  await page.getByLabel('Import sourced case JSON').setInputFiles({name:'mismatched-capital.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(request))});
  await expect(page.locator('.defence-error[role=alert]')).toContainText('identical initial capital');
  await page.getByRole('button',{name:'Synthetic demonstration',exact:true}).click();
  await page.getByText('Define a new hypothetical scenario',{exact:true}).click();
  await page.getByRole('button',{name:'Add hypothetical scenario',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Enter an explicit return');
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'test-results/defence-mobile.png',caret:'initial'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.getByRole('button',{name:'Observed research',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Evidence required before calculation'})).toBeVisible();
  expect(errors).toEqual([]);console.log('Portfolio defence browser, UI-to-Python reproduction, safeguards and responsive checks passed.');
}finally{await browser.close();}
