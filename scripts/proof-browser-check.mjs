import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
const browser=await chromium.launch({headless:true,channel:'msedge'});
try {
  fs.mkdirSync('test-results',{recursive:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:3000/proof-scale');
  await expect(page.getByRole('heading',{name:/Evidence before expansion/})).toBeVisible();
  await expect(page.locator('#proof-gates .proof-gate')).toHaveCount(4);
  await expect(page.locator('#proof-gates').getByText('not assessed',{exact:true})).toHaveCount(4);
  await expect(page.getByText('No authoritative evidence is registered. All critical decisions remain blocked.',{exact:true})).toBeVisible();
  await expect(page.getByText('Private approval workspace is not connected.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Vectis ONE',exact:true}).click();
  await page.getByRole('button',{name:'Load synthetic example',exact:true}).click();
  await expect(page.getByText('Synthetic demonstration — all evidence and economics below are invented.',{exact:true})).toBeVisible();
  await expect(page.getByText('250 · forecast',{exact:true})).toBeVisible();
  await expect(page.getByText('Commercial profitability: not established.',{exact:true})).toBeVisible();
  await expect(page.locator('#scope').getByText('Expansion blocked',{exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/proof-scale-desktop.png',caret:'initial'});
  const exportRequest=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export offline evaluation request',exact:true}).click();
  const requestPath='test-results/proof-scale-ui-request.json';await (await exportRequest).saveAs(requestPath);
  const run=spawnSync('python',['-m','worker.proof_scale',requestPath],{encoding:'utf8'});
  if(run.status!==0)throw new Error(run.stderr||run.stdout||'Python evaluation failed');
  const report=JSON.parse(run.stdout);
  if(report.executionAuthority!=='none'||report.vectis.realisedProfitGbp!==null||report.vectis.avoidedExpenditureGbp!==null||report.vectis.commercialProfitEstablished!==false)throw new Error('Python promoted unverified or synthetic values');
  fs.writeFileSync('test-results/proof-scale-ui-report.json',JSON.stringify(report,null,2));
  const repeat=spawnSync('python',['-m','worker.proof_scale',requestPath],{encoding:'utf8'});
  if(repeat.status!==0||repeat.stdout!==run.stdout)throw new Error('Financial calculations are not reproducible');
  await page.getByRole('button',{name:'Append reconciled demo revision',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Earlier evidence and gate decisions remain unchanged');
  await expect(page.locator('#integrity tbody tr')).toHaveCount(5);
  await page.getByRole('button',{name:'Inspect earlier cutoff',exact:true}).click();
  await expect(page.getByText('Excluded at this cutoff',{exact:true})).toHaveCount(1);
  await page.getByRole('button',{name:'Return to current cutoff',exact:true}).click();
  const exportSource=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export source package',exact:true}).click();
  const sourcePath='test-results/proof-scale-source-package.json';await (await exportSource).saveAs(sourcePath);
  const source=JSON.parse(fs.readFileSync(sourcePath,'utf8'));source.evidence[0].mode='forward';
  await page.getByLabel('Import evidence package JSON').setInputFiles({name:'mixed-mode.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(source))});
  await expect(page.getByRole('status')).toContainText('Historical, synthetic and forward evidence cannot be combined');
  await expect(page.getByRole('button',{name:'Approve only this increment'})).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'test-results/proof-scale-mobile.png',caret:'initial'});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw new Error('Proof & Scale mobile overflow');
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('Proof & Scale browser checks passed: four blocked gates, synthetic isolation, forecast/profit separation, immutable revisions, historical exclusions, Python handoff/reproducibility and mobile layout.');
}finally{await browser.close();}
